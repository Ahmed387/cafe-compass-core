const escapeRe = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const COMPILED: Array<{ re: RegExp; ar: string }> = DB_ERRORS_AR.map(([en, ar]) => {
  const pattern = en
    .split("%%")
    .map((part) => part.split("%").map(escapeRe).join("(.+?)"))
    .join("%");
  // The message may be followed by " · details" (see rawMessage in format.ts).
  return { re: new RegExp(`^${pattern}(?:\\s*·|$)`, "i"), ar };
});

/** Arabic text for a database message, or null when it isn't one we know. */
export function dbErrorToArabic(message: string): string | null {
  const text = message.trim();
  for (const { re, ar } of COMPILED) {
    const m = text.match(re);
    if (m) return ar.replace(/\{(\d)\}/g, (_, n: string) => (m[Number(n)] ?? "").trim());
  }
  return null;
}

